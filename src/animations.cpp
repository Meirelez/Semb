void initial() {
    TickType_t xLastWakeTime = xTaskGetTickCount();
    const TickType_t xFrequency = pdMS_TO_TICKS(100);
    BaseType_t xWasDelayed;

	grid_clear();

	for (int n = 0; n < 3; n++) {
        auto f = (void (*[])(int, int)){grid_setX, grid_setY, grid_setZ}[n];
		f(0, HIGH);
		delay(200);
		for (int m = 1; m < 6; m++) {
            f(m - 1, LOW);
			f(m, HIGH);
			delay(200);
		}
		for (int m = 5; m > 0; m--) {
            f(m, LOW);
            f(m - 1, HIGH);
            delay(200);
        }
        f(0, LOW);
		delay(1000);
	}

	grid_clear();
}

static int character(int c, int w, int h);

void print(char *msg) {
    TickType_t xLastWakeTime = xTaskGetTickCount();
    const TickType_t xFrequency = pdMS_TO_TICKS(100);
    BaseType_t xWasDelayed;

    grid_clear();
    if (!msg || strlen(msg) < 1)
        return;

    for (int y = 2; y < 6; y++)
        for (int z = 0; z < 6; z++)
            grid_set(0, y, z, character(msg[0], y, z));

    for (int c = 4; c < 4*strlen(msg); c++) {
        for (int y = 0; y < 6; y++)
            for (int z = 0; z < 6; z++)
                grid_set(0, y, z, y != 5 ? grid_get(0, y+1, z) : character(msg[c/4], c%4, z));

        xWasDelayed = xTaskDelayUntil(&xLastWakeTime, xFrequency);
    }

    grid_clear();
}

static int character(int c, int w, int h) {
    uint8_t r = font_PGM[6*(c-0x20) +5 -h];
    return (r & (1<<(4-w-1))) >> (4-w-1);
}


